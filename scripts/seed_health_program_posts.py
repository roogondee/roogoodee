def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="แสดงว่าจะเขียนอะไร แต่ไม่เขียนจริง")
    args = ap.parse_args()

    sb = create_client(SUPABASE_URL, SUPABASE_KEY)
    slugs = [p["slug"] for p in POSTS]

    # on_conflict="slug" เขียนทับเงียบ ๆ — เช็กก่อนว่าแถวที่มีอยู่เป็นของเราจริง
    existing = sb.table("posts").select("slug, service, status").in_("slug", slugs).execute().data or []
    for row in existing:
        if row.get("service") != "foreign":
            print(f"หยุด: slug '{row['slug']}' มีอยู่แล้วและเป็น service='{row.get('service')}' "
                  f"— ไม่เขียนทับ กรุณาเปลี่ยน slug ในสคริปต์นี้ก่อน")
            return 1
        print(f"จะอัปเดตทับของเดิม: {row['slug']} (status ปัจจุบัน = {row.get('status')})")

    for post in POSTS:
        row = {
            "title": post["title"],
            "slug": post["slug"],
            "content": post["content"].strip(),
            "excerpt": post["meta_desc"][:300],
            "service": "foreign",
            "category": CATEGORY,
            "focus_kw": post["focus_kw"],
            "meta_desc": post["meta_desc"],
            "image_url": "",
            # draft เสมอ — ให้คนรีวิวใน /admin ก่อน sitemap กรอง published อยู่แล้ว
            "status": "draft",
            "published_at": None,
        }
        if args.dry_run:
            print(f"[dry-run] {row['slug']} — {len(row['content'])} ตัวอักษร")
            continue
        sb.table("posts").upsert(row, on_conflict="slug").execute()
        print(f"บันทึกเป็นฉบับร่างแล้ว: {row['slug']}")

    if not args.dry_run:
        print("\nเปิด /admin เพื่อรีวิวและกด publish เมื่อพร้อม")
    return 0


if __name__ == "__main__":
    sys.exit(main())
